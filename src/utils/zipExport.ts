import JSZip from 'jszip';
import { GeneratedProject } from '../types/agent';

function slug(name: string): string {
  return name.toLowerCase().replace(/[^a-z0-9]+/g, '_').replace(/^_+|_+$/g, '') || 'hai_app';
}

export async function exportProjectZip(project: GeneratedProject) {
  const zip = new JSZip();

  const readme = `# ${project.name}

Generated by **H.AI Multi-Agent Autonomous Platform** in ${project.durationSeconds} seconds
(${project.source === 'ai' ? `Gemini · ${project.aiModel || 'live'}` : 'deterministic demo engine'}).

${project.spec?.tagline || ''}

## Platforms
- Web: ${project.spec?.stack.web || project.code.web.framework}
- iOS: ${project.spec?.stack.ios || project.code.ios.framework}
- Android: ${project.spec?.stack.android || project.code.android.framework}
- Backend: ${project.spec?.stack.backend || 'Supabase PostgreSQL + RLS'}

## Live URLs
- Vercel: ${project.vercel.deployUrl}
- Supabase: ${project.supabase.projectUrl}

## Run the web app
\`\`\`bash
cd web
npm install
npm run dev
\`\`\`

## Database
Open the Supabase SQL editor and run \`supabase/schema.sql\`, then \`supabase/seed.sql\`.

## Deploy
\`\`\`bash
cd web && npm run build
npx vercel --prod
\`\`\`

## Verification
${(project.quality || []).map((q) => `- ${q.passed ? '✅' : '⚠️'} ${q.label}: ${q.detail}`).join('\n') || '- no checks recorded'}

## اردو ہدایات
یہ پراجیکٹ H.AI کے 30 پروفیشنل ایجنٹس نے خودکار تیار کیا ہے۔
ویب کے لیے \`web\` فولڈر میں \`npm install\` چلائیں، iOS کے لیے Xcode میں \`ios\`، اور Android کے لیے Android Studio میں \`android\` کھولیں۔
ڈیٹا بیس کا مکمل SQL \`supabase/schema.sql\` میں موجود ہے۔
`;

  zip.file('README.md', readme);
  zip.file('hai-project.json', JSON.stringify({
    id: project.id,
    name: project.name,
    prompt: project.prompt,
    timestamp: project.timestamp,
    source: project.source,
    model: project.aiModel,
    platforms: project.platforms,
    spec: project.spec,
    quality: project.quality,
    deploys: project.deploys,
  }, null, 2));

  if (project.files && project.files.length > 0) {
    project.files.forEach((file) => zip.file(file.path, file.content));
  } else {
    const webFolder = zip.folder('web');
    if (webFolder) {
      webFolder.file('package.json', project.code.web.packageJson);
      webFolder.file('src/App.tsx', project.code.web.mainComponent);
      webFolder.file('src/index.css', project.code.web.appCss);
    }
    const iosFolder = zip.folder('ios');
    if (iosFolder) {
      iosFolder.file('App/ContentView.swift', project.code.ios.contentViewSwift);
      iosFolder.file('App/App.swift', project.code.ios.appSwift);
      iosFolder.file('Podfile', project.code.ios.podfile);
    }
    const androidFolder = zip.folder('android');
    if (androidFolder) {
      androidFolder.file('app/src/main/java/com/hai/app/MainActivity.kt', project.code.android.mainActivityKt);
      androidFolder.file('app/build.gradle.kts', project.code.android.buildGradle);
    }
    const supabaseFolder = zip.folder('supabase');
    if (supabaseFolder) {
      supabaseFolder.file('schema.sql', project.supabase.databaseSql);
    }
  }

  if (project.previewHtml) {
    zip.file('preview/index.html', project.previewHtml);
  }

  const blob = await zip.generateAsync({ type: 'blob' });
  const downloadUrl = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = downloadUrl;
  a.download = `${slug(project.name)}_hai_source.zip`;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(downloadUrl);
}
