import type { GeneratedFile, Platform } from './types';

function slugify(s: string) {
  return s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '').slice(0, 40) || 'my-app';
}

export function buildFiles(prompt: string, platform: Platform): GeneratedFile[] {
  const slug = slugify(prompt);
  const title = prompt.length > 60 ? prompt.slice(0, 60) + '…' : prompt;

  const webApp = `// ${title} — generated by H.AI (web)
export default function App() {
  return (
    <main style={{ fontFamily: 'system-ui', padding: 32, maxWidth: 720, margin: '0 auto' }}>
      <h1>${escapeHtml(title)}</h1>
      <p>Prompt: ${escapeHtml(prompt)}</p>
      <p>This starter was generated by the H.AI 30-agent factory.</p>
      <ul>
        <li>✅ Responsive layout</li>
        <li>✅ Auth-ready (Supabase)</li>
        <li>✅ Deploy-ready (Vercel)</li>
      </ul>
    </main>
  );
}`;

  const webIndex = `<!doctype html>
<html><head><meta charset="utf-8"/><meta name="viewport" content="width=device-width,initial-scale=1"/>
<title>${escapeHtml(title)}</title></head>
<body><div id="root"></div><script type="module" src="/src/main.tsx"></script></body></html>`;

  const api = `// Supabase Edge Function stub — H.AI
// Deploy: supabase functions deploy ${slug}
export async function handler(req: Request) {
  const { prompt } = await req.json().catch(() => ({ prompt: "${escapeHtml(prompt.slice(0, 80))}" }));
  return Response.json({ ok: true, app: "${slug}", echo: prompt });
}`;

  const schema = `-- Supabase schema — H.AI auto-generated
create table if not exists public.users (
  id uuid primary key default gen_random_uuid(),
  email text unique not null,
  created_at timestamptz default now()
);
create table if not exists public.projects (
  id uuid primary key default gen_random_uuid(),
  owner uuid references public.users(id),
  title text not null,
  prompt text not null,
  created_at timestamptz default now()
);
alter table public.projects enable row level security;
create policy "owners read own" on public.projects for select using (auth.uid() = owner);`;

  const readme = `# ${title}\n\n> Generated by H.AI J.A.R.V.I.S. Factory from prompt:\n> "${prompt}"\n\n## Run\n\`\`\`bash\nnpm install\nnpm run dev\n\`\`\`\n\n## Deploy\n- Web → Vercel: \`vercel --prod\`\n- DB → Supabase: \`supabase db push\`\n- iOS/Android sources included under \`/native\`.\n`;

  if (platform === 'web') {
    return [
      { path: 'index.html', language: 'html', content: webIndex, platform, description: 'Web app entry point' },
      { path: 'src/App.tsx', language: 'tsx', content: webApp, platform, description: 'Generated React application' },
      { path: 'supabase/schema.sql', language: 'sql', content: schema, platform: 'backend', description: 'Supabase database schema' },
      { path: 'supabase/functions/app/index.ts', language: 'ts', content: api, platform: 'backend', description: 'Supabase Edge Function' },
      { path: 'README.md', language: 'md', content: readme, platform, description: 'Project setup and deployment instructions' },
    ];
  }

  if (platform === 'ios') {
    const swift = `// ${title} — SwiftUI starter by H.AI
import SwiftUI
struct ContentView: View {
    var body: some View {
        NavigationStack {
            VStack(spacing: 16) {
                Text("${escapeHtml(title)}").font(.largeTitle.bold())
                Text("${escapeHtml(prompt.slice(0, 120))}").foregroundStyle(.secondary)
                Button("Get Started") {}
                    .buttonStyle(.borderedProminent)
            }.padding()
            .navigationTitle("${slug}")
        }
    }
}`;
    return [
      { path: 'ios/ContentView.swift', language: 'swift', content: swift, platform, description: 'iOS SwiftUI application' },
      { path: 'supabase/schema.sql', language: 'sql', content: schema, platform: 'backend', description: 'Supabase database schema' },
      { path: 'README.md', language: 'md', content: readme, platform, description: 'Project setup and deployment instructions' },
    ];
  }

  const kotlin = `// ${title} — Jetpack Compose starter by H.AI
package com.hai.${slug.replace(/-/g, '')}
import androidx.compose.material3.*
import androidx.compose.runtime.Composable
@Composable
fun App() {
    MaterialTheme {
        Text("${escapeHtml(title)}")
        Text("${escapeHtml(prompt.slice(0, 120))}")
    }
}`;
  return [
    { path: 'android/App.kt', language: 'kotlin', content: kotlin, platform, description: 'Android Jetpack Compose application' },
    { path: 'supabase/schema.sql', language: 'sql', content: schema, platform: 'backend', description: 'Supabase database schema' },
    { path: 'README.md', language: 'md', content: readme, platform, description: 'Project setup and deployment instructions' },
  ];
}

function escapeHtml(s: string) {
  return s.replace(/[<>&"]/g, (c) => ({ '<': '&lt;', '>': '&gt;', '&': '&amp;', '"': '&quot;' }[c]!));
}

export function previewHtml(prompt: string): string {
  const safe = escapeHtml(prompt);
  return `<!doctype html><html><body style="margin:0;font-family:system-ui;background:#020a11;color:#e2f3ff;display:flex;align-items:center;justify-content:center;min-height:100vh">
<div style="max-width:560px;padding:32px;border:1px solid #67e8f9;border-radius:16px;background:#071522">
<h1 style="color:#67e8f9">⚡ H.AI Preview</h1><p>${safe}</p>
<button style="background:#67e8f9;border:0;padding:10px 18px;border-radius:10px;font-weight:700">Get Started</button>
<p style="opacity:.6;font-size:12px">Generated UI preview — deploy to Vercel for full app</p></div></body></html>`;
}

/** Try Gemini for a richer README/plan. Falls back to local template on any error. */
export async function enhanceWithGemini(prompt: string, platform: Platform): Promise<string | null> {
  const key = import.meta.env.VITE_GEMINI_API_KEY as string | undefined;
  if (!key) return null;
  try {
    const { GoogleGenAI } = await import('@google/genai');
    const ai = new GoogleGenAI({ apiKey: key });
    const res = await ai.models.generateContent({
      model: 'gemini-2.0-flash',
      contents: `You are H.AI architect. In 8 bullet points, give a build plan for a ${platform} app from this idea: "${prompt}". Include data model, screens, APIs, auth, tests, deploy steps. Keep it short.`,
    });
    return (res as unknown as { text?: string }).text ?? null;
  } catch {
    return null;
  }
}
